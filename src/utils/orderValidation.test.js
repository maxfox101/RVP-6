import { describe, expect, it } from "vitest";
import { digits, errorFor, formatPhone } from "./orderValidation.js";

describe("digits — только цифры из телефона", () => {
  // TC-09. Скобки, пробелы, плюс и дефисы из маски убираются, остаются 11 цифр.
  it("TC-09: убирает скобки, пробелы и плюс", () => {
    expect(digits("+7 (999) 123 - 45 - 67")).toBe("79991234567");
  });

  // TC-10. Пустая строка и null дают пустой результат, а не ошибку.
  it("TC-10: пустая строка даёт пустой результат", () => {
    expect(digits("")).toBe("");
    expect(digits(null)).toBe("");
  });
});

describe("formatPhone — маска +7", () => {
  // TC-11. Номер с 8 в начале приводится к маске +7 (999) 123 - 45 - 67.
  it("TC-11: форматирует полный номер", () => {
    expect(formatPhone("89991234567")).toBe("+7 (999) 123 - 45 - 67");
  });

  // TC-12. Если номер начинается не с 7 и не с 8, код 7 подставляется сам.
  it("TC-12: подставляет 7, если номер начинается не с 7/8", () => {
    expect(formatPhone("9991234567")).toBe("+7 (999) 123 - 45 - 67");
  });

  // TC-13. Пустое поле остаётся пустым и не превращается в «+7».
  it("TC-13: пустой ввод остаётся пустым", () => {
    expect(formatPhone("")).toBe("");
  });
});

describe("errorFor — валидация заявки (требования R3–R5)", () => {
  // TC-01 (R3). Пустое имя нельзя отправить: функция возвращает «Заполните имя.»
  it("TC-01 (R3): пустое имя — ошибка", () => {
    expect(errorFor("name", "")).toBe("Заполните имя.");
  });

  // TC-14 (R3). Одна буква слишком короткая — нужно не меньше двух.
  it("TC-14 (R3): короткое/неверное имя — ошибка", () => {
    expect(errorFor("name", "A")).toMatch(/не меньше 2/);
  });

  // TC-02 (R3). Обычное имя «Иван» проходит без сообщения об ошибке.
  it("TC-02 (R3): нормальное имя — без ошибки", () => {
    expect(errorFor("name", "Иван")).toBe("");
  });

  // TC-03 (R4). Недописанный телефон «+7 (999)» отклоняется.
  it("TC-03 (R4): неполный телефон — ошибка", () => {
    expect(errorFor("phone", "+7 (999)")).toMatch(/полностью/);
  });

  // TC-04 (R4). Полный номер из 11 цифр считается корректным.
  it("TC-04 (R4): полный телефон — без ошибки", () => {
    expect(errorFor("phone", "+7 (999) 123 - 45 - 67")).toBe("");
  });

  // TC-15 (R5). Пробелы вместо адреса — то же, что пустое поле.
  it("TC-15 (R5): пустой email — ошибка", () => {
    expect(errorFor("email", "  ")).toBe("Заполните e-mail.");
  });

  // TC-05 (R5). Строка без @ и домена не принимается как почта.
  it("TC-05 (R5): битый email — ошибка", () => {
    expect(errorFor("email", "not-mail")).toMatch(/корректный e-mail/);
  });

  // TC-16 (R5). Обычный адрес user@mail.ru проходит без ошибки.
  it("TC-16 (R5): корректный email — без ошибки", () => {
    expect(errorFor("email", "user@mail.ru")).toBe("");
  });
});
